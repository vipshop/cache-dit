"""Numerical and compile coverage for cache-dit's native FP8 operators."""

import pytest
import torch
import torch.nn.functional as F

from cache_dit.kernels import fp8_gemm
from cache_dit.kernels import fp8_quantize

pytestmark = pytest.mark.skipif(
  not torch.cuda.is_available() or torch.cuda.get_device_capability() < (10, 0),
  reason="cache-dit FP8 GEMM requires sm100 or newer",
)


def _dequantize(q: torch.Tensor, scale: torch.Tensor, mode: str, is_weight: bool) -> torch.Tensor:
  """Dequantize one FP8 tensor with the public scale contract.

  :param q: Quantized tensor.
  :param scale: Scale generated by :func:`fp8_quantize`.
  :param mode: Granularity name.
  :param is_weight: Whether the tensor is a ``[N, K]`` weight.
  :returns: Floating-point dequantized tensor.
  """

  qf = q.float()
  if mode == "per_row":
    return qf * scale[:, None]
  if mode == "per_tensor":
    return qf * scale[0]
  if not is_weight:
    expanded = scale.repeat_interleave(128, dim=1)[:, :q.shape[1]]
    return qf * expanded
  expanded = scale.repeat_interleave(128, dim=0).repeat_interleave(128, dim=1)
  return qf * expanded[:q.shape[0], :q.shape[1]]


def _relative_l2(actual: torch.Tensor, expected: torch.Tensor) -> float:
  """Return relative L2 error.

  :param actual: Test tensor.
  :param expected: Reference tensor.
  :returns: Relative L2 error.
  """

  diff = (actual.float() - expected.float()).norm()
  return float(diff / expected.float().norm().clamp_min(1e-12))


@pytest.mark.parametrize("mode", ["per_row", "per_tensor", "per_block"])
def test_quantize_dequantize_matches_torch_reference(mode: str) -> None:
  torch.manual_seed(0)
  x = torch.randn(17, 256, dtype=torch.bfloat16, device="cuda")
  q, scale = fp8_quantize(x, mode=mode)
  if mode == "per_row":
    scale_ref = x.float().abs().amax(dim=-1) / 448.0
    q_ref = x.float() / scale_ref[:, None]
    expected = (q_ref.clamp(-448, 448).to(torch.float8_e4m3fn).float() * scale_ref[:, None])
    assert torch.allclose(scale, scale_ref)
  elif mode == "per_tensor":
    scale_ref = x.float().abs().amax() / 448.0
    q_ref = x.float() / scale_ref
    expected = q_ref.clamp(-448, 448).to(torch.float8_e4m3fn).float() * scale_ref
    assert torch.allclose(scale, scale_ref.reshape(1))
  else:
    scale_ref = x.float().reshape(17, 2, 128).abs().amax(dim=-1) / 448.0
    q_ref = x.float().reshape(17, 2, 128) / scale_ref[:, :, None]
    expected = (q_ref.clamp(-448, 448).to(torch.float8_e4m3fn).float() *
                scale_ref[:, :, None]).reshape(17, 256)
    assert torch.allclose(scale, scale_ref)
  assert _relative_l2(_dequantize(q, scale, mode, False), expected) < 2e-3


@pytest.mark.parametrize("m,n,k", [(1, 8, 16), (5, 24, 48), (129, 264, 144)])
@pytest.mark.parametrize("mode", ["per_row", "per_tensor"])
def test_linear_matches_dequantized_reference_with_tails_and_bias(mode: str, m: int, n: int,
                                                                  k: int) -> None:
  torch.manual_seed(1)
  a = torch.randn(m, k, dtype=torch.bfloat16, device="cuda")
  w = torch.randn(n, k, dtype=torch.bfloat16, device="cuda")
  bias = torch.randn(n, dtype=torch.bfloat16, device="cuda")
  qa, sa = fp8_quantize(a, mode)
  qw, sw = fp8_quantize(w, mode, is_weight=True)
  if mode == "per_tensor":
    assert torch.allclose(sa, (a.float().abs().amax() / 448.0).reshape(1))
    assert torch.allclose(sw, (w.float().abs().amax() / 448.0).reshape(1))
  actual = fp8_gemm(qa, qw, sa, sw, bias=bias, mode=mode)
  expected = F.linear(
    _dequantize(qa, sa, mode, False).float(),
    _dequantize(qw, sw, mode, True).float(), bias.float())
  assert _relative_l2(actual, expected) < 3e-3


@pytest.mark.parametrize("m,n,k", [(7, 136, 256), (129, 384, 512)])
def test_per_block_linear_with_output_tail(m: int, n: int, k: int) -> None:
  torch.manual_seed(2)
  a = torch.randn(m, k, dtype=torch.bfloat16, device="cuda")
  w = torch.randn(n, k, dtype=torch.bfloat16, device="cuda")
  qa, sa = fp8_quantize(a, "per_block")
  qw, sw = fp8_quantize(w, "per_block", is_weight=True)
  actual = fp8_gemm(qa, qw, sa, sw, mode="per_block")
  expected = F.linear(
    _dequantize(qa, sa, "per_block", False).float(),
    _dequantize(qw, sw, "per_block", True).float())
  assert _relative_l2(actual, expected) < 2e-3


@pytest.mark.parametrize("mode", ["per_row", "per_tensor", "per_block"])
def test_zero_rows_are_exactly_zero(mode: str) -> None:
  m, n, k = 8, 32, 128
  a = torch.zeros(m, k, dtype=torch.bfloat16, device="cuda")
  w = torch.randn(n, k, dtype=torch.bfloat16, device="cuda")
  qa, sa = fp8_quantize(a, mode)
  qw, sw = fp8_quantize(w, mode, is_weight=True)
  actual = fp8_gemm(qa, qw, sa, sw, mode=mode)
  assert torch.isfinite(actual).all()
  assert torch.equal(actual, torch.zeros_like(actual))


def test_cuda_graph_replay_matches_eager() -> None:
  torch.manual_seed(3)
  m, n, k = 64, 256, 256
  a = torch.randn(m, k, dtype=torch.bfloat16, device="cuda")
  w = torch.randn(n, k, dtype=torch.bfloat16, device="cuda")
  qa, sa = fp8_quantize(a, "per_block")
  qw, sw = fp8_quantize(w, "per_block", is_weight=True)
  side_stream = torch.cuda.Stream()
  side_stream.wait_stream(torch.cuda.current_stream())
  with torch.cuda.stream(side_stream):
    for _ in range(2):
      fp8_gemm(qa, qw, sa, sw, mode="per_block")
  torch.cuda.current_stream().wait_stream(side_stream)
  graph = torch.cuda.CUDAGraph()
  with torch.cuda.graph(graph):
    captured = fp8_gemm(qa, qw, sa, sw, mode="per_block")
  expected = fp8_gemm(qa, qw, sa, sw, mode="per_block")
  graph.replay()
  assert _relative_l2(captured, expected) < 1e-6

  new_a = torch.randn_like(a)
  new_qa, new_sa = fp8_quantize(new_a, "per_block")
  qa.copy_(new_qa)
  sa.copy_(new_sa)
  expected = fp8_gemm(qa, qw, sa, sw, mode="per_block")
  graph.replay()
  assert _relative_l2(captured, expected) < 1e-6


def test_fake_and_fullgraph_compile() -> None:
  from torch._subclasses.fake_tensor import FakeTensorMode

  m, n, k = 11, 40, 128
  a = torch.randn(m, k, dtype=torch.bfloat16, device="cuda")
  w = torch.randn(n, k, dtype=torch.bfloat16, device="cuda")
  with FakeTensorMode():
    fake_a = torch.empty(m, k, dtype=torch.bfloat16, device="cuda")
    fake_w = torch.empty(n, k, dtype=torch.float8_e4m3fn, device="cuda")
    qa, sa = fp8_quantize(fake_a, "per_row")
    out = fp8_gemm(qa, fake_w, sa, torch.empty(n, dtype=torch.float32, device="cuda"), None)
    assert out.shape == (m, n) and out.dtype == torch.bfloat16

  def run(a, w):
    qa, sa = fp8_quantize(a, "per_row")
    qw, sw = fp8_quantize(w, "per_row", is_weight=True)
    return fp8_gemm(qa, qw, sa, sw, mode="per_row")

  compiled = torch.compile(run, fullgraph=True)
  expected = run(a, w)
  actual = compiled(a, w)
  assert _relative_l2(actual, expected) < 1e-4
