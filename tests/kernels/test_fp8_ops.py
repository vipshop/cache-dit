def _dequantize(q: torch.Tensor, scale: torch.Tensor, mode: str, is_weight: bool) -> torch.Tensor:
  """Dequantize one FP8 tensor with the public scale contract.

  :param q: Quantized tensor.
  :param scale: Scale generated by :func:`fp8_quantize`.
  :param mode: Granularity name.
  :param is_weight: Whether the tensor is a ``[N, K]`` weight.
  :returns: Floating-point dequantized tensor.
  """

  qf = q.float()
  if mode == "per_row":
    return qf * scale[:, None]
  if mode == "per_tensor":
    return qf * scale[0]
  if not is_weight:
    expanded = scale.repeat_interleave(128, dim=1)[:, :q.shape[1]]
    return qf * expanded
  expanded = scale.repeat_interleave(128, dim=0).repeat_interleave(128, dim=1)
  return qf * expanded[:q.shape[0], :q.shape[1]]


def _relative_l2(actual: torch.Tensor, expected: torch.Tensor) -> float:
  """Return relative L2 error.

  :param actual: Test tensor.
  :param expected: Reference tensor.
  :returns: Relative L2 error.
  """

  diff = (actual.float() - expected.float()).norm()
  return float(diff / expected.float().norm().clamp_min(1e-12))


@pytest.mark.parametrize("mode", ["per_row", "per_tensor", "per_block"])
def test_quantize_dequantize_matches_torch_reference(mode: str) -> None:
  torch.manual_seed(0)
  x = torch.randn(17, 256, dtype=torch.bfloat16, device="cuda")
  q, scale = fp8_quantize(x, mode=mode)
  if mode == "per_row":
    scale_ref = x.float().abs().amax(dim=-1) / 448.0
    q_ref = x.float() / scale_ref[:, None]
    expected = (q_ref.clamp(-448, 448).to(torch.float8_e4m3fn).float() * scale_ref[:, None])
    assert torch.allclose(scale, scale_ref)
  elif mode == "per_tensor":
    scale_ref = x.float().abs().amax() / 448.0
    q_ref = x.float() / scale_ref
    expected = q_ref.clamp(-448, 448).to(torch.float8_e4m3fn).float() * scale_ref
    assert torch.allclose(scale, scale_ref.reshape(1))
  else:
    scale_ref = x.float().reshape(17, 2, 128).abs().amax(dim=-1) / 448.0
    q_ref = x.float().reshape(17, 2, 128) / scale_ref[:, :, None]
    expected = (q_ref.clamp(-448, 448).to(torch.float8_e4m3fn).float() *
                scale_ref[:, :, None]).reshape(17, 256)
    assert torch.allclose(scale, scale_ref)
  assert _relative_l2(_dequantize(q, scale, mode, False), expected) < 2e-3


@pytest.mark.parametrize("mode", ["per_row", "per_tensor", "per_block"])
def test_compiled_torch_quantize_matches_custom(mode: str) -> None:
  torch.manual_seed(9)
  x = torch.randn(257, 3072, dtype=torch.bfloat16, device="cuda")
  x[0].zero_()
  compiled = torch.compile(lambda value: fp8_quantize_torch(value, mode), fullgraph=True)
  q_compiled, s_compiled = compiled(x)
  q_custom, s_custom = fp8_quantize(x, mode)
  assert torch.equal(q_compiled, q_custom)
  assert torch.equal(s_compiled, s_custom)


