@pytest.mark.parametrize("use_ws", [True, False])
@pytest.mark.parametrize("mode", ["per_row", "per_block"])
def test_cuda_graph_replay_matches_eager(use_ws: bool, mode: str) -> None:
  torch.manual_seed(3)
  m, n, k = 64, 256, 256
  a = torch.randn(m, k, dtype=torch.bfloat16, device="cuda")
  w = torch.randn(n, k, dtype=torch.bfloat16, device="cuda")
  qa, sa = fp8_quantize(a, mode)
  qw, sw = fp8_quantize(w, mode, is_weight=True)
  side_stream = torch.cuda.Stream()
  side_stream.wait_stream(torch.cuda.current_stream())
  with torch.cuda.stream(side_stream):
    for _ in range(2):
      fp8_gemm(qa, qw, sa, sw, mode=mode, use_ws=use_ws, use_native=True)
  torch.cuda.current_stream().wait_stream(side_stream)
  graph = torch.cuda.CUDAGraph()
  with torch.cuda.graph(graph):
    captured = fp8_gemm(qa, qw, sa, sw, mode=mode, use_ws=use_ws, use_native=True)
  expected = fp8_gemm(qa, qw, sa, sw, mode=mode, use_ws=use_ws, use_native=True)
  graph.replay()
  assert _relative_l2(captured, expected) < 1e-6

  new_a = torch.randn_like(a)
  new_qa, new_sa = fp8_quantize(new_a, mode)
  qa.copy_(new_qa)
  sa.copy_(new_sa)
  expected = fp8_gemm(qa, qw, sa, sw, mode=mode, use_ws=use_ws, use_native=True)
  graph.replay()
  assert _relative_l2(captured, expected) < 1e-6


@pytest.mark.parametrize("use_ws", [True, False])
def test_fake_and_fullgraph_compile(use_ws: bool) -> None:
  from torch._subclasses.fake_tensor import FakeTensorMode

  m, n, k = 11, 40, 128
  a = torch.randn(m, k, dtype=torch.bfloat16, device="cuda")
  w = torch.randn(n, k, dtype=torch.bfloat16, device="cuda")
  with FakeTensorMode():
    fake_a = torch.empty(m, k, dtype=torch.bfloat16, device="cuda")
    fake_w = torch.empty(n, k, dtype=torch.float8_e4m3fn, device="cuda")
    qa, sa = fp8_quantize(fake_a, "per_row")
    out = fp8_gemm(qa,
                   fake_w,
                   sa,
                   torch.empty(n, dtype=torch.float32, device="cuda"),
                   None,
                   use_ws=use_ws)
    assert out.shape == (m, n) and out.dtype == torch.bfloat16

  def run(a, w):
    qa, sa = fp8_quantize(a, "per_row")
    qw, sw = fp8_quantize(w, "per_row", is_weight=True)
    return fp8_gemm(qa, qw, sa, sw, mode="per_row", use_ws=use_ws)

  compiled = torch.compile(run, fullgraph=True)
  expected = run(a, w)
  actual = compiled(a, w)
  assert _relative_l2(actual, expected) < 1e-4


